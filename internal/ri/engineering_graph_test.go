	if err != nil {
		t.Fatal(err)
	}
	if first.Digest != second.Digest || first.Coverage != "PARTIAL" {
		t.Fatalf("graph was not deterministic/partial: %s %s %s", first.Digest, second.Digest, first.Coverage)
	}
