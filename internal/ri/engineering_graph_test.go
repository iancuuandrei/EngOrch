func graphInput(path, source string, pkg GoPackageBinding, declarations []GoSymbol, imports []GoImport, calls []GoCall, markers []string, producer string) GoGraphFileInput {
	content := []byte(source)
	sourceSum := sha256.Sum256(content)
	facts := GoFileFacts{
		Schema: goFactsSchema, Language: "go", ParserVersion: goFactsParserVersion,
		Path: path, SourceSHA256: hex.EncodeToString(sourceSum[:]), ProducerSHA256: producer,
		SyntaxErrors: false, Coverage: "PARTIAL", Declarations: declarations,
		Imports: imports, Calls: calls, GeneratedMarkers: markers, Cache: "miss", ParseCount: 1,
	}
	var err error
	facts.CacheKey, err = canonical.Hash("harness.ri.go-file-facts.v1", map[string]any{
		"schema": goFactsSchema, "language": "go", "parser": goFactsParserVersion,
		"path": path, "source_sha256": facts.SourceSHA256, "producer_sha256": producer,
	})
	if err != nil {
		panic(err)
	}
	body := facts
	body.BodySHA256 = ""
	body.Cache = ""
	body.ParseCount = 0
	bodyBytes, err := canonical.Bytes(body)
	if err != nil {
		panic(err)
	}
	bodySum := sha256.Sum256(bodyBytes)
	facts.BodySHA256 = hex.EncodeToString(bodySum[:])
	return GoGraphFileInput{Facts: facts, Source: content, Package: pkg}
}

func graphSpan(source, text string, from int) GoRange {
	start := strings.Index(source[from:], text)
	if start < 0 {
		panic("fixture text not found: " + text)
	}
	start += from
	return GoRange{StartByte: start, EndByte: start + len(text)}
}

