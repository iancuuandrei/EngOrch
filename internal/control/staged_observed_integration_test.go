// This file owns ONLY the genuine observed-signal integration gap left by
// TestStagedObservedPreparationReplayRoundTrip: that test has no admitted RI
// (advisory fallback only) and its substitution check compares bytes without
// submitting the mutation to the replay validator. The tests below use an
// exact source-bound admitted PlannerGoContext (real Git commit/tree via
// repository.Discover, real RI admission via AdmitPlannerGoContext through the
// existing Append/Replay seam) with staged selector 3, and every substitution
// is passed through Replay or the replay validator.
//
// Helpers use the soi prefix to avoid collisions. This file deliberately does
// not call observedFixtureIdentity (its signature may become t-aware).

func soiRequireRIBinary(t *testing.T) (string, string) {
	t.Helper()
	exe := os.Getenv("ENGORCH_RI_BINARY")
	if exe == "" {
		t.Skip("NOTRUN: missing ENGORCH_RI_BINARY binding for genuine RI admission; cannot build source-bound PlannerGoContext without the pinned offline parser")
	}
	cleaned := filepath.Clean(exe)
	bin, err := os.ReadFile(cleaned)
	if err != nil {
		t.Fatalf("RI binary unreadable: %v", err)
	}
	sum := sha256.Sum256(bin)
	return cleaned, hex.EncodeToString(sum[:])
}

